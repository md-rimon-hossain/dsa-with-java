public class UpdateArray {
    public static void updateArr(int arr[]) {
        for (int i = 0; i < arr.length; i++) {
            arr[i] = arr[i] + 1;
        }
    }

    public static void callUpdateArr() {
        int arr[] = { 90, 91, 92 };
        updateArr(arr);
        for (int i = 0; i < arr.length; i++) {
            System.out.print(arr[i] + " ");
        }
        System.out.println();
    }

    public static void main(String[] args) {
        callUpdateArr();
    }
}
